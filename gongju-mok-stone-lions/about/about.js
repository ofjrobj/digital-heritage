(() => {
  const dialog = document.getElementById('process-gallery');
  if (!dialog || typeof dialog.showModal !== 'function') return;

  const image = dialog.querySelector('.gallery-image');
  const title = dialog.querySelector('#gallery-title');
  const intro = dialog.querySelector('#gallery-intro');
  const links = dialog.querySelector('.gallery-links');
  const figure = dialog.querySelector('.gallery-figure');
  const bottom = dialog.querySelector('.gallery-bottom');
  const caption = dialog.querySelector('#gallery-caption');
  const count = dialog.querySelector('.gallery-count');
  const previous = dialog.querySelector('[data-gallery-previous]');
  const next = dialog.querySelector('[data-gallery-next]');
  const close = dialog.querySelector('[data-gallery-close]');
  let current;
  let index = 0;
  let opener;

  function render() {
    const hasImages = current.items.length > 0;
    dialog.dataset.hasImages = String(hasImages);
    figure.hidden = bottom.hidden = !hasImages;
    intro.textContent = current.description || '';
    intro.hidden = !current.description;
    links.replaceChildren();
    (current.links || []).forEach(reference => {
      const link = document.createElement('a');
      link.href = reference.url;
      link.target = '_blank';
      link.rel = 'noopener noreferrer';
      link.textContent = reference.label;
      link.setAttribute('aria-label', `${reference.label} (새 탭)`);
      links.append(link);
    });
    links.hidden = !links.childElementCount;
    dialog.setAttribute('aria-describedby', current.description ? 'gallery-intro' : 'gallery-caption');
    if (!hasImages) {
      image.removeAttribute('src');
      image.alt = '';
      caption.textContent = '';
      count.textContent = '';
      previous.hidden = next.hidden = true;
      return;
    }
    const [file, alt, description] = current.items[index];
    image.src = './assets/' + file;
    image.alt = alt;
    dialog.querySelector('[data-gallery-original]').href = image.src;
    caption.textContent = description;
    count.textContent = `${index + 1} / ${current.items.length}`;
    previous.setAttribute('aria-disabled', String(index === 0));
    next.setAttribute('aria-disabled', String(index === current.items.length - 1));
    previous.hidden = next.hidden = current.items.length < 2;
  }

  function move(offset) {
    const position = index + offset;
    if (position < 0 || position >= current.items.length) return;
    index = position;
    render();
  }

  document.querySelectorAll('[data-gallery]').forEach(link => {
    link.addEventListener('click', event => {
      if (event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) return;
      const gallery = processGalleries.find(item => item.id === link.dataset.gallery);
      if (!gallery) return;
      event.preventDefault();
      current = gallery;
      index = 0;
      opener = link;
      title.textContent = current.title;
      render();
      dialog.showModal();
      dialog.scrollTop = 0;
      document.body.classList.add('gallery-open');
      close.focus({preventScroll: true});
    });
  });

  previous.addEventListener('click', () => move(-1));
  next.addEventListener('click', () => move(1));
  close.addEventListener('click', () => dialog.close());
  dialog.addEventListener('keydown', event => {
    if (event.key === 'ArrowLeft' || event.key === 'ArrowRight') {
      event.preventDefault();
      move(event.key === 'ArrowLeft' ? -1 : 1);
    }
  });
  dialog.addEventListener('click', event => {
    if (event.target !== dialog) return;
    const rect = dialog.getBoundingClientRect();
    if (event.clientX < rect.left || event.clientX > rect.right ||
        event.clientY < rect.top || event.clientY > rect.bottom) dialog.close();
  });
  dialog.addEventListener('close', () => {
    document.body.classList.remove('gallery-open');
    opener?.focus({preventScroll: true});
  });
})();

// Numbered navigation follows the production stages without opening a new page.
(() => {
  const tabs = [...document.querySelectorAll('.timeline-tabs [role="tab"]')];
  const panels = [...document.querySelectorAll('.process-timeline')];
  const steps = [...document.querySelectorAll('.production-list > li[id]')];
  if (!tabs.length || !steps.length) return;

  function select(tab, focus = false) {
    tabs.forEach(item => {
      const selected = item === tab;
      item.setAttribute('aria-selected', String(selected));
      item.tabIndex = selected ? 0 : -1;
    });
    panels.forEach(panel => { panel.hidden = panel.id !== tab.getAttribute('aria-controls'); });
    if (focus) tab.focus();
  }

  tabs.forEach((tab, index) => {
    tab.addEventListener('click', () => select(tab));
    tab.addEventListener('keydown', event => {
      let next;
      if (event.key === 'ArrowRight') next = (index + 1) % tabs.length;
      if (event.key === 'ArrowLeft') next = (index + tabs.length - 1) % tabs.length;
      if (event.key === 'Home') next = 0;
      if (event.key === 'End') next = tabs.length - 1;
      if (next === undefined) return;
      event.preventDefault();
      select(tabs[next], true);
    });
  });

  const links = [...document.querySelectorAll('.process-timeline a')];
  let selectedStepId;
  function mark(id) {
    selectedStepId = id;
    links.forEach(link => {
      const active = link.getAttribute('href') === '#' + id;
      link.parentElement.classList.toggle('is-current', active);
      if (active) link.setAttribute('aria-current', 'step');
      else link.removeAttribute('aria-current');
    });
  }
  links.forEach(link => link.addEventListener('click', () => mark(link.hash.slice(1))));

  let scheduled = false;
  function update() {
    scheduled = false;
    const threshold = Math.min(220, window.innerHeight * .3);
    const visible = steps.filter(step => {
      const rect = step.getBoundingClientRect();
      return rect.bottom > 0 && rect.top < window.innerHeight;
    });
    const current = visible.find(step => step.getBoundingClientRect().bottom > threshold);
    if (current) {
      const rowTop = current.getBoundingClientRect().top;
      const selectedInRow = visible.find(step => step.id === selectedStepId &&
        Math.abs(step.getBoundingClientRect().top - rowTop) < 2);
      mark((selectedInRow || current).id);
    }
  }
  window.addEventListener('scroll', () => {
    if (!scheduled) { scheduled = true; requestAnimationFrame(update); }
  }, {passive: true});
  const hashed = steps.find(step => '#' + step.id === window.location.hash);
  if (hashed) select(tabs.find(tab => tab.id === 'timeline-tab-' + hashed.dataset.productionTrack));
  update();
})();

// A short, non-blocking notice when entering this work-in-progress page.
(() => {
  const notice = document.getElementById('preparation-notice');
  if (!notice) return;
  let timer;
  function show() {
    clearTimeout(timer);
    notice.hidden = false;
    notice.classList.add('is-visible');
    timer = setTimeout(() => {
      notice.hidden = true;
      notice.classList.remove('is-visible');
    }, 5800);
  }
  (document.fonts?.ready || Promise.resolve()).then(show);
  window.addEventListener('pageshow', event => { if (event.persisted) show(); });
  window.addEventListener('pagehide', () => {
    clearTimeout(timer);
    notice.hidden = true;
    notice.classList.remove('is-visible');
  });
})();
